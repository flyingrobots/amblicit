import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';
import path from 'node:path';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');

const root = path.dirname(fileURLToPath(import.meta.url));
const pagePath = path.join(root, 'index.html');
const snapshot = JSON.parse(await fs.readFile(path.join(root, 'snapshot.json'), 'utf8'));
const expectedEdges = snapshot.edges.map(e=>`${e.source}->${e.target}`).sort();
const output = process.env.DAG_CHECK_OUTPUT;
if (output) await fs.mkdir(output,{recursive:true});
const screenshot = async (page, name) => { if(output) await page.screenshot({path:path.join(output,name),fullPage:true}); };
const browser = await chromium.launch({headless:true, timeout:30000, ...(process.env.CHROMIUM_EXECUTABLE ? {executablePath:process.env.CHROMIUM_EXECUTABLE} : {}), args:['--disable-gpu']});
const deadline = setTimeout(async()=>{await browser.close();process.exitCode=1;},60000);
try {
  const context = await browser.newContext({viewport:{width:1600,height:1050},offline:true});
  const page = await context.newPage();
  const errors=[],requests=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('request', r=>{if(r.url().startsWith('http')) requests.push(r.url());});
  await page.goto(pathToFileURL(pagePath).href);
  await page.waitForSelector('.task-node',{timeout:3000});
  assert.equal(await page.locator('.task-node').count(),snapshot.nodes.length);
  assert.equal(await page.locator('path.dependency').count(),snapshot.edges.length);
  const rendered=await page.locator('path.dependency').evaluateAll(es=>es.map(e=>`${e.dataset.from}->${e.dataset.to}`).sort());
  assert.deepEqual(rendered,expectedEdges,'Only native must-finish-before relationships may become edges');
  assert(!rendered.includes('identity->counterparts'));
  const embedded=await page.locator('#graph-data').textContent().then(JSON.parse);
  assert(!embedded.nodes.some(n=>n.number===288 && n.project==='amblicit'));
  await page.locator('#view-waves').click();
  assert.equal(await page.locator('#wave-table tbody tr').count(),9);
  assert.equal(await page.locator('.wave-card').count(),snapshot.nodes.length);
  const waveMembership=await page.locator('.wave-card').evaluateAll(es=>es.map(e=>e.dataset.id).sort());
  assert.deepEqual(waveMembership,snapshot.nodes.map(n=>n.id).sort());
  assert.equal(await page.locator('#width-exact').textContent(),'9');
  assert.equal(await page.locator('#width-wave').textContent(),'8');
  await page.locator('#preview-toggle').check();
  assert.equal(await page.locator('.simulate-finish:enabled').count(),4);
  await page.locator('.wave-card[data-id="list_publish"] .simulate-finish').focus();
  await page.keyboard.press('Enter');
  assert(await page.locator('.wave-card[data-id="list_publish"] .wave-task').evaluate(e=>e===document.activeElement),'Completion must retain keyboard focus in the completed task card');
  assert.equal(await page.locator('.wave-card[data-id="identity"] .simulate-finish').isEnabled(),true,'No wave barrier after a predecessor completes');
  assert.equal(await page.locator('.wave-card[data-id="model"] .simulate-finish').isEnabled(),true);
  assert.equal(await page.locator('.wave-card[data-id="list_runtime"] .simulate-finish').isEnabled(),false,'All prerequisites must be complete');
  await page.locator('#preview-maximum').click();
  assert.equal(await page.locator('.simulate-finish:enabled').count(),9);
  await screenshot(page,'dag-waves.png');
  await page.locator('#preview-reset').click();
  await page.locator('#preview-toggle').uncheck();
  await page.locator('#view-graph').click();
  assert.equal(new Set(await page.locator('.node-card').evaluateAll(es=>es.map(e=>getComputedStyle(e).fill))).size,3);
  await screenshot(page,'dag-desktop.png');
  await page.locator('#node-rope').click();
  assert.match(await page.locator('#detail-title').textContent(),/ReplaceRange/);
  await page.locator('#scope').selectOption('before');
  assert.equal(await page.locator('#node-model').isVisible(),false,'Broader optics must not block the first rope proof');
  assert.equal(await page.locator('#node-identity').isVisible(),true);
  const visible=await page.locator('path.dependency:visible').evaluateAll(es=>es.map(e=>`${e.dataset.from}->${e.dataset.to}`));
  assert(visible.every(e=>expectedEdges.includes(e)),'Focus must never invent transitive edges');
  await screenshot(page,'dag-focused.png');
  await page.locator('#reset').click();
  await page.locator('[data-project="echo"]').first().click();
  assert.equal(await page.locator('.task-node:visible').count(),snapshot.nodes.length,'Project spotlight must keep prerequisite context');
  assert.equal(await page.locator('.task-node.spotlight').count(),snapshot.nodes.filter(n=>n.project==='echo').length);
  await page.locator('#search').fill('no-such-task-at-all');
  assert.match(await page.locator('#match-status').textContent(),/No matching tasks/);
  await page.locator('#reset').click();
  await page.locator('#view-list').click();
  await page.locator('#search').fill('jedit#296');
  assert.equal(await page.locator('#task-table tbody tr:visible').count(),1);
  assert.match(await page.locator('#task-table tbody tr:visible').textContent(),/ReplaceRange/);
  await page.locator('#reset').click();
  await page.locator('#view-graph').click();
  const before = await page.locator('#scene').getAttribute('transform');
  await page.locator('#zoom-in').click();
  assert.notEqual(await page.locator('#scene').getAttribute('transform'),before);
  const settleResize=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const zoomed=await page.locator('#scene').getAttribute('transform');
  await page.setViewportSize({width:1400,height:950});await settleResize();
  assert.equal(await page.locator('#scene').getAttribute('transform'),zoomed,'Resize must retain user zoom');
  await page.locator('#fit').click();
  const fitted = await page.locator('#scene').getAttribute('transform');
  const rect = await page.locator('#graph').boundingBox();
  await page.mouse.move(rect.x+20,rect.y+rect.height-20);
  await page.mouse.down(); await page.mouse.move(rect.x+95,rect.y+rect.height-65,{steps:5}); await page.mouse.up();
  assert.notEqual(await page.locator('#scene').getAttribute('transform'),fitted);
  const panned=await page.locator('#scene').getAttribute('transform');
  await page.setViewportSize({width:1200,height:900});await settleResize();
  assert.equal(await page.locator('#scene').getAttribute('transform'),panned,'Resize must retain user pan');
  await page.locator('#fit').click();
  const refitted=await page.locator('#scene').getAttribute('transform');
  await page.setViewportSize({width:1600,height:1050});await settleResize();
  assert.notEqual(await page.locator('#scene').getAttribute('transform'),refitted,'Fit must restore automatic resizing');
  await page.locator('#node-model').focus(); await page.keyboard.press('Enter');
  assert.match(await page.locator('#detail-title').textContent(),/specify places/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#details').isVisible(),false);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#fit').click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile must not overflow horizontally');
  await screenshot(page,'dag-mobile.png');
  await page.locator('#view-list').click();
  assert.equal(await page.locator('#task-table tbody tr:visible').count(),snapshot.nodes.length);
  await page.locator('#theme').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.setViewportSize({width:1600,height:1050});
  await page.locator('#view-graph').click(); await page.locator('#fit').click();
  await screenshot(page,'dag-light.png');
  const downloadEvent=page.waitForEvent('download');
  await page.locator('#download-data').click();
  const download=await downloadEvent;
  const exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  assert.deepEqual(exported.edges.map(e=>`${e.source}->${e.target}`).sort(),expectedEdges);
  await page.locator('#node-model').click();
  await page.locator('#scope').selectOption('after');
  assert.equal(await page.locator('#node-rope').isVisible(),false);
  assert.equal(await page.locator('#node-rope_optics').isVisible(),true);
  await page.locator('#reset').click();
  await page.locator('#node-rope_optics').click();
  await page.locator('#scope').selectOption('chain');
  assert.equal(await page.locator('.task-node:visible').count(),snapshot.nodes.length);
  const mobile=await context.newPage();
  await mobile.setViewportSize({width:390,height:844});
  await mobile.goto(pathToFileURL(pagePath).href);
  await mobile.waitForFunction(()=>document.querySelector('#zoom-label').textContent==='85%');
  const heading=await mobile.locator('h1').boundingBox(),theme=await mobile.locator('#theme').boundingBox();
  assert(heading.y+heading.height<theme.y||theme.x>heading.x+heading.width);
  await screenshot(mobile,'dag-mobile-initial.png');
  await mobile.locator('#view-waves').click();
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert(await mobile.locator('.wave-table-wrap').evaluate(e=>e.scrollWidth>e.clientWidth));
  assert.deepEqual(errors,[]);
  assert.deepEqual(requests,[],'The page must work without a server, CDN or network');
  console.log(JSON.stringify({pass:true,nodes:snapshot.nodes.length,nativeEdges:snapshot.edges.length,checks:['snapshot graph equality and direction','no hierarchy or synthetic edges','three project colors','prerequisite focus','project context','search and empty state','list alternative','zoom and pan','keyboard selection','mobile width','light theme','offline and no JavaScript errors','export fidelity','dependent and whole-chain focus','mobile initial zoom','MECE wave rendering','rolling readiness without barriers','maximum frontier example','mobile waves scrolling']}));
} finally {clearTimeout(deadline);await browser.close();}
